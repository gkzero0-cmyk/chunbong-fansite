import fs from 'node:fs';
import assert from 'node:assert/strict';
const css=fs.readFileSync(new URL('../chunbak.css',import.meta.url),'utf8');
assert.ok(css.includes('grid-template-columns'));
assert.ok(css.includes('minmax(0,460px)')||css.includes('minmax(0, 460px)'), 'desktop center column should allow the larger board');
assert.ok(css.includes('min(100%,460px)')||css.includes('min(100%, 460px)'), 'desktop board should expand to 460px');
assert.ok(css.includes('@media (max-width:900px)')||css.includes('@media (max-width: 900px)'));
assert.ok(css.includes('min(calc(100vw - 28px),460px)')||css.includes('min(calc(100vw - 28px), 460px)'), 'mobile board should stay within viewport');
assert.equal(css.includes('overflow-x:hidden'),false);
assert.ok(css.includes('touch-action:none')||css.includes('touch-action: none'));
assert.ok(css.includes('@media (max-width:520px)')||css.includes('@media (max-width: 520px)'));
assert.ok(css.includes('padding-inline:12px')||css.includes('padding-inline: 12px'));
assert.ok(css.includes('.chunbak-left,.chunbak-right{display:contents}')||css.includes('.chunbak-left, .chunbak-right{display: contents}'), 'mobile rails must flatten so game appears before ranking/legend');
assert.ok(css.includes('.chunbak-stats{order:1}'));
assert.ok(css.includes('.chunbak-center{order:2}'));
assert.ok(css.includes('.chunbak-next-card{order:3}'));
assert.ok(css.includes('.chunbak-ranking{order:4}'));
assert.ok(css.includes('.chunbak-evolution{order:5}'));
assert.ok(css.includes('.chunbak-modal{align-items:end;padding:0}')||css.includes('.chunbak-modal{align-items:end;padding:0;'), 'mobile modal should become a bottom sheet');
console.log('chunbak responsive regression passed');
