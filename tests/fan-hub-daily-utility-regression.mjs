import assert from 'node:assert/strict';
import fs from 'node:fs';
const read=file=>fs.readFileSync(new URL('../'+file,import.meta.url),'utf8');
const personal=read('personal-hub.js');
const data=read('data-core.js');
const home=read('home-overview.js');
const search=read('site-improvements.js');
const changelog=read('changelog-data.js');
assert.doesNotThrow(()=>new Function(personal));
assert.doesNotThrow(()=>new Function(data));
assert.doesNotThrow(()=>new Function(home));
for(const label of ['나중에 보기','웃긴 방송','마크 명장면','다시 보고 싶은 콘텐츠'])assert.ok(personal.includes(label),label+' collection missing');
for(const label of ['LIVE 시작','타로 방송','마인크래프트','합방','특별 콘텐츠'])assert.ok(personal.includes(label),label+' alert preference missing');
for(const lead of ['5분 전','10분 전','30분 전'])assert.ok(personal.includes(lead),lead+' reminder option missing');
assert.match(personal,/challengeProgress/);
assert.match(personal,/dailyStreak/);
assert.match(data,/data-calendar-related/,'broadcast calendar related-media block missing');
assert.match(data,/query\.get\('date'\)/,'broadcast calendar date deep link missing');
assert.match(data,/document\.querySelectorAll\('\[data-calendar-date\]'\)\.forEach/,'broadcast calendar must bind all date buttons');
assert.match(data,/state\.selectedCalendarDate='';/,'calendar month navigation must clear stale selected date');
assert.match(data,/url\.searchParams\.delete\('date'\)/,'calendar month navigation must clear stale date deep link');
assert.match(search,/kind:'방송 기록'/,'search must index broadcast sessions');
assert.match(search,/kind:'방송 카테고리'/,'search must index categories');
assert.match(home,/LAST 30 DAYS/);
assert.match(home,/THIS WEEK/);
assert.match(home,/TOP CATEGORY/);
assert.match(changelog,/오늘 대시보드·알림·검색·아카이브·개인화 7종 확장/);
assert.doesNotMatch(changelog,/팬사이트 상태 페이지|STATUS PAGE/,'excluded status page must not be introduced');
console.log('fan hub daily utility upgrades regression passed');
