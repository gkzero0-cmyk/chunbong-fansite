import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
import fs from 'node:fs';
const require=createRequire(import.meta.url);
const core=require('../lib/chunbong-content-archive-core');
const seed=JSON.parse(fs.readFileSync(new URL('../data/chunbong-contents-seed.json',import.meta.url),'utf8'));
const item=seed.items.find(row=>row.id==='leopel');
assert.ok(item,'leopel seed must exist');
const normalized=core.normalizeArchiveItem(item);
assert.equal(normalized.participantCount,671);
assert.ok(normalized.knowledgeSections.length>=8,'leopel knowledge guide should include reusable overview, locations and economy sections');
assert.ok(normalized.knowledgeSections.some(row=>row.kind==='story'&&row.images.length),'story section should carry contextual images');
const publicItem=core.toPublicArchiveItem(normalized);
assert.ok(publicItem.sources.every(row=>!/nemopix/i.test(String(row.label)+' '+String(row.url))),'Nemopix must stay internal');
assert.ok(publicItem.knowledgeSections.some(row=>row.title==='세계관 · 공동 목표'));
assert.ok(publicItem.knowledgeSections.some(row=>row.title==='주요 지역 · 공간'));
assert.ok(publicItem.knowledgeSections.some(row=>row.title==='경제 · 후원 연동'));
assert.ok((item.media||[]).filter(row=>['trailer-pv','leopel-vod-165343833','leopel-vod-167705699'].includes(row.id)).every(row=>/res\.cloudinary\.com/.test(row.thumbnail||'')),'Leopel SOOP thumbnails should be permanent Cloudinary assets');
const client=fs.readFileSync(new URL('../chunbong-contents.js',import.meta.url),'utf8');
assert.match(client,/function renderKnowledgeArchive/);
assert.match(client,/data-knowledge-image-src/);
assert.match(client,/function referenceGuideRows/);
assert.match(client,/DOCUMENT KNOWLEDGE/);
assert.match(client,/data-guide-image-source/);
const api=fs.readFileSync(new URL('../lib/chunbong-content-archive-api.js',import.meta.url),'utf8');
assert.match(api,/function extractNamuStructured/);
assert.match(api,/refreshReferenceGuides/);
assert.match(api,/persistNotionGuideMedia/);
assert.match(api,/persistReferenceGuideMedia/);
assert.match(api,/CLOUDINARY_URL/);
const archiveApi=require('../lib/chunbong-content-archive-api');
assert.equal(archiveApi._internals.cloudinaryArchiveKey({sourceUrl:'https://example.com/image.png?sig=one'}),archiveApi._internals.cloudinaryArchiveKey({sourceUrl:'https://example.com/image.png?sig=two'}),'signed URL changes should not duplicate Notion assets');
assert.notEqual(
  archiveApi._internals.cloudinaryArchiveKey({originUrl:'https://file.namu.moe/file/one',sourceUrl:'https://namu.wiki/w/test'}),
  archiveApi._internals.cloudinaryArchiveKey({originUrl:'https://file.namu.moe/file/two',sourceUrl:'https://namu.wiki/w/test'}),
  'reference images from one NamuWiki page must receive distinct permanent asset keys'
);
const namu=archiveApi._internals.extractNamuStructured('<h2>주요 지역</h2><p>레오펠 광장</p><img src="/images/plaza.webp" alt="레오펠 광장">','https://namu.wiki/w/%EB%A0%88%EC%98%A4%ED%8E%A0');
assert.equal(namu.sections[0].title,'주요 지역');
assert.match(namu.sections[0].text,/레오펠 광장/);
assert.equal(namu.sections[0].images[0].alt,'레오펠 광장');
const namuSource='https://namu.wiki/w/%EB%A0%88%EC%98%A4%ED%8E%A0?from=LEOPEL';
const namuTransport=archiveApi._internals.namuReadTransportUrl(namuSource);
assert.equal(namuTransport?.hostname,'d.namu.moe','NamuWiki 403 fallback may use the read transport internally');
assert.equal(namuTransport?.pathname,'/w/%EB%A0%88%EC%98%A4%ED%8E%A0','fallback transport must preserve the original NamuWiki document path');
assert.equal(namuTransport?.search,'?from=LEOPEL','fallback transport must preserve query parameters');
const namuFallbackMeta=archiveApi._internals.fetchNamuMeta(new URL(namuSource),'<title>레오펠</title><h2>주요 지역</h2><p>광장 안내</p>');
assert.equal(namuFallbackMeta.url,namuSource,'fallback-parsed metadata must keep the public source URL on namu.wiki');
assert.ok(!/namu\.moe/i.test(namuFallbackMeta.url),'read transport must never leak into the public source URL');
assert.match(api,/persistArchiveGuideImage\(media,itemId,'reference'\)/,'reference images should be persisted in a separate permanent asset namespace');
assert.equal(core.blockedArchiveSourceUrl('https://d.namu.moe/w/%EB%A0%88%EC%98%A4%ED%8E%A0'),true,'Namu mirror transport must remain blocked from public source lists');
const normalizedNotion=core.normalizeArchiveItem({...item,notionSections:[{id:'n1',title:'순서 테스트',content:[{type:'text',text:'앞 문단'},{type:'image',image:{src:'https://example.com/a.png',filename:'guide.png'}},{type:'text',text:'뒤 문단'}]}]});
assert.deepEqual(normalizedNotion.notionSections[0].content.map(block=>block.type),['text','image','text']);
const normalizedReference=core.normalizeArchiveItem({...item,referenceSections:[{id:'r1',sourceId:'source-reference',pageTitle:'나무위키 · 레오펠',title:'주요 지역',provider:'namuwiki',text:'지역 설명',images:[{src:'https://example.com/leopel-map.png',alt:'레오펠 전체 지도',sourceUrl:'https://namu.wiki/w/%EB%A0%88%EC%98%A4%ED%8E%A0',provider:'namuwiki'}],content:[{type:'text',text:'지역 설명'},{type:'image',image:{src:'https://example.com/leopel-map.png',alt:'레오펠 전체 지도',sourceUrl:'https://namu.wiki/w/%EB%A0%88%EC%98%A4%ED%8E%A0',provider:'namuwiki'}}]}]});
assert.equal(normalizedReference.referenceSections[0].provider,'namuwiki');
assert.deepEqual(normalizedReference.referenceSections[0].content.map(block=>block.type),['text','image']);
assert.equal(core.toPublicArchiveItem(normalizedReference).referenceSections[0].sourceId,'source-reference');
console.log('content knowledge archive checks passed');
